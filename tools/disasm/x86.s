; ============================================================================
; X86-64 INSTRUCTION DECODER
; ============================================================================
; Decodes one instruction and writes it in Intel syntax, in the same style
; as `objdump -d -M intel`, so the two can be compared line by line:
;
;     x86_decode(code, available, address, fmtbuf) -> length, branch target
;
; Coverage (stage 1): legacy prefixes, REX, the one-byte map and the 0F map
; for general-purpose instructions (ALU, mov/lea/xchg, push/pop, shifts,
; mul/div, inc/dec/not/neg, test/cmp, jumps/calls/ret, setcc/cmovcc/jcc,
; movzx/movsx/movsxd, bt*, bsf/bsr, shld/shrd, cmpxchg/xadd, bswap,
; string instructions with rep, nop forms, syscall, cpuid, rdtsc, ...).
; Everything else - SSE/AVX, 0F 38 / 0F 3A, x87 - decodes as "(bad)"
; (length 0) for now.
;
; The opcode tables are generated by scripts/gen_x86_tables.py into
; x86_tables.inc; the FM_* / FL_* numbers below must match that script.
;
; Calling convention (AMD64):
;   args  : rdi, rsi, rdx, rcx
;   callee saved: rbx, rbp, r12-r15

; ---- operand forms (FORMS in scripts/gen_x86_tables.py) ----
%define FM_NONE      0
%define FM_EbGb      1
%define FM_EvGv      2
%define FM_GbEb      3
%define FM_GvEv      4
%define FM_ALIb      5
%define FM_eAXIz     6
%define FM_Zv        7
%define FM_ZbIb      8
%define FM_ZvIv      9
%define FM_Jb       10
%define FM_Jz       11
%define FM_Eb       12
%define FM_Ev       13
%define FM_EbIb     14
%define FM_EvIz     15
%define FM_EvIb     16
%define FM_Eb1      17
%define FM_Ev1      18
%define FM_EbCL     19
%define FM_EvCL     20
%define FM_EbIbU    21
%define FM_EvIbU    22
%define FM_GvM      23
%define FM_GvEvIz   24
%define FM_GvEvIb   25
%define FM_GvEb     26
%define FM_GvEw     27
%define FM_GvEd     28
%define FM_IbU      29
%define FM_IbS      30
%define FM_Iz       31
%define FM_Iw       32
%define FM_ZvXchg   33
%define FM_EvGv_bt  34
%define FM_EvGvIb   35
%define FM_EvGvCL   36
%define FM_STR      37
%define FM_XCHG90   38
%define FM_CBW      39
%define FM_CWD      40
%define FM_Ewv      41          ; sldt/str/...: register at operand size, memory WORD
%define FM_G7       42          ; 0F 01: system instructions (sgdt, rdtscp, ...)
%define FM_GAE      43          ; 0F AE: fences, fxsave, ldmxcsr, clflush, ...
; SSE-family forms (V = xmm/mm from ModRM.reg, W = xmm/mm or memory from
; ModRM.rm, U = register-only rm, M = memory-only rm, E/G = general register)
%define FM_VW       44
%define FM_WV       45
%define FM_VWI      46
%define FM_VE       47
%define FM_EV       48
%define FM_GW       49
%define FM_GU       50
%define FM_UI       51          ; shift-by-immediate group (0F 71/72/73)
%define FM_VM       52
%define FM_MV       53
%define FM_V12      54          ; movlps/movhps (memory) or movhlps/movlhps
%define FM_EVI      55
%define FM_VEI      56
%define FM_GUI      57
%define FM_VW0      58          ; blendv*: implicit xmm0 third operand
%define FM_CMPS     59          ; cmpps & co: imm < 8 becomes cmpltps & co
%define FM_PCLMUL   60
%define FM_ENDBR    61
; VEX-only forms (x86_vex0f / x86_vex38 / x86_vex3a)
%define FM_XBCAST   62          ; broadcast: V (xmm/ymm by L), xmm or memory
%define FM_XINS     63          ; vinsert*128: ymm, ymm, xmm/m128, imm8
%define FM_XEXT     64          ; vextract*128: xmm/m128, ymm, imm8
%define FM_XIS4     65          ; vblendv*: V, vvvv, W, register in imm8[7:4]
%define FM_BGBE     66          ; BMI: gpr, vvvv gpr, r/m
%define FM_BGEB     67          ; BMI: gpr, r/m, vvvv gpr
%define FM_BBE      68          ; BMI group: vvvv gpr, r/m
