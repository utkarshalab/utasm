    jmp     .done

.f_g9:                                     ; 0F C7
    movzx   eax, byte [rel dx_regno]
    and     eax, 7
    cmp     byte [rel dx_mod], 3
    je      .g9_reg
    cmp     eax, 1                         ; cmpxchg8b m64 / cmpxchg16b m128
    jne     .sys_bad
    lea     rsi, [rel s_cmpxchg8b]
    mov     ebx, 64
    test    byte [rel dx_rex], 8
    jz      .g9_mem
    lea     rsi, [rel s_cmpxchg16b]
    mov     ebx, 0x180                     ; OWORD PTR
.g9_mem:
    mov     [rel dx_mnem], rsi
    mov     esi, 1
    call    dx_mnemonic
    mov     edi, ebx
    call    dx_mem
    jmp     .done
.g9_reg:                                   ; rdrand / rdseed r16/32/64
    lea     rsi, [rel s_rdrand]
    cmp     eax, 6
    je      .g9_rput
    lea     rsi, [rel s_rdseed]
    cmp     eax, 7
    jne     .sys_bad
.g9_rput:
    mov     [rel dx_mnem], rsi
    mov     esi, 1
    call    dx_mnemonic
    mov     edi, ebx
    movzx   esi, byte [rel dx_rmreg]
    call    dx_reg
    jmp     .done
.unknown_form:
    mov     byte [rel dx_fail], 1
    jmp     .done

.f_Ewv:                                    ; register at operand size, memory WORD
    mov     esi, 1
    call    dx_mnemonic
    mov     edi, ebx
    cmp     byte [rel dx_mod], 3
    je      .ewv_put
    mov     edi, 16
.ewv_put:
    call    dx_rm
    jmp     .done

.f_g7:                                     ; 0F 01
    cmp     byte [rel dx_mod], 3
    je      .g7_reg
    lea     rsi, [rel g7_mem_names]
    lea     rdi, [rel g7_mem_sizes]
    jmp     .sys_mem
.g7_reg:
    ; smsw r / lmsw r (reg 4 / 6), else the whole ModRM byte selects it
    movzx   eax, byte [rel dx_regno]
    and     eax, 7
    cmp     eax, 4
    je      .g7_msw
    cmp     eax, 6
    je      .g7_msw
    lea     rsi, [rel g7_reg_names]
    movzx   eax, byte [rel dx_modrm]
.g7_scan:
    movzx   ecx, byte [rsi]
    test    ecx, ecx
    jz      .sys_bad
    cmp     ecx, eax
    je      .g7_found
    add     rsi, 16
    jmp     .g7_scan
.g7_found:
    inc     rsi
    mov     [rel dx_mnem], rsi
    jmp     .f_none
.g7_msw:
    shl     eax, 4
    lea     rsi, [rel g7_mem_names]
    add     rsi, rax
    mov     [rel dx_mnem], rsi
    cmp     byte [rel dx_regno], 6         ; lmsw takes a 16-bit register
    jne     .f_E
    and     byte [rel dx_regno], 7
    mov     ebx, 16
    jmp     .f_E

.f_gae:                                    ; 0F AE
    cmp     byte [rel dx_mod], 3
    je      .gae_reg
    lea     rsi, [rel gae_mem_names]
    lea     rdi, [rel gae_mem_sizes]
    jmp     .sys_mem
.gae_reg:                                  ; lfence / mfence / sfence
    movzx   eax, byte [rel dx_regno]
    and     eax, 7
    cmp     eax, 5
    jb      .sys_bad
    lea     rsi, [rel gae_reg_names]
    lea     rsi, [rsi + rax*8 - 40]
    mov     [rel dx_mnem], rsi
    jmp     .f_none

.sys_mem:                                  ; rsi = 16-byte name slots, rdi = sizes
    movzx   eax, byte [rel dx_regno]
    and     eax, 7
    movzx   ecx, byte [rdi + rax]
    cmp     ecx, 0xFF
    je      .sys_bad
    shl     eax, 4
    add     rsi, rax
    mov     [rel dx_mnem], rsi
    push    rcx
    push    rcx
    mov     esi, 1
    call    dx_mnemonic
    pop     rdi
    pop     rdi
    call    dx_mem                         ; edi = size (0 = none)
    jmp     .done
.sys_bad:
    mov     byte [rel dx_fail], 1
    jmp     .done

.f_none:
    xor     esi, esi
    call    dx_mnemonic
    jmp     .done

.f_EG:                                     ; r/m, reg
    mov     esi, 1
    call    dx_mnemonic
    mov     edi, ebx
    call    dx_rm
    call    dx_sep
    mov     edi, ebx
    call    dx_greg
    jmp     .done

.f_GE:                                     ; reg, r/m
    mov     esi, 1
    call    dx_mnemonic
    mov     edi, ebx
    call    dx_greg
    call    dx_sep
    mov     edi, ebx
    call    dx_rm
    jmp     .done

.f_accI:                                   ; al, imm8 / ax|eax|rax, imm16|32
    cmp     byte [rel dx_form], FM_ALIb
    jne     .acc_z
    call    dx_rd8
    jmp     .acc_have
.acc_z:
    call    .read_imm_z
.acc_have:
    push    rax
    mov     esi, 1
    call    dx_mnemonic
    mov     edi, ebx
    xor     esi, esi
    call    dx_reg
    call    dx_sep
    pop     rsi
    call    dx_imm
    jmp     .done

.f_Zv:                                     ; register in the opcode
    mov     esi, 1
    call    dx_mnemonic
    mov     edi, ebx
    call    dx_opreg
    jmp     .done

.f_ZI:                                     ; r8 in opcode, imm8
    call    dx_rd8
    push    rax
    mov     esi, 1
    call    dx_mnemonic
    mov     edi, 8
    call    dx_opreg
    call    dx_sep
    pop     rsi
    call    dx_imm
    jmp     .done

.f_ZvIv:                                   ; mov r, imm16/32 - or movabs r64, imm64
    cmp     ebx, 64
    jne     .zv_small
    call    dx_rd64
    push    rax
    lea     rax, [rel s_movabs]
    mov     [rel dx_mnem], rax
    jmp     .zv_print
.zv_small:
    call    .read_imm_z
    push    rax
.zv_print:
    mov     esi, 1
    call    dx_mnemonic
    mov     edi, ebx
    call    dx_opreg
    call    dx_sep
    pop     rsi
    call    dx_imm
    jmp     .done

.f_Jb:
    call    dx_rd8
    movsx   rax, al
    jmp     .jump
.f_Jz:
    call    dx_rd32
    movsxd  rax, eax
.jump:
    push    rax
    mov     esi, 1
    call    dx_mnemonic
    pop     rsi
    call    dx_branch
    jmp     .done

.f_E:                                      ; r/m
    mov     esi, 1
    call    dx_mnemonic
    mov     edi, ebx
    call    dx_rm
    jmp     .done

.f_EI:                                     ; r/m, imm (Ib sign-extended / Iz)
    movzx   eax, byte [rel dx_form]
    cmp     eax, FM_EvIz
    je      .ei_z
    call    dx_rd8
    movsx   rax, al
    jmp     .ei_have
.ei_z:
    call    .read_imm_z
.ei_have:
    push    rax
    mov     esi, 1
    call    dx_mnemonic
    mov     edi, ebx
    call    dx_rm
    call    dx_sep
    pop     rsi
    call    dx_imm
    jmp     .done

.f_E1:                                     ; r/m, 1
    mov     esi, 1
    call    dx_mnemonic
    mov     edi, ebx
    call    dx_rm
    lea     rsi, [rel s_comma1]
    call    dx_puts
    jmp     .done

.f_ECL:                                    ; r/m, cl
    mov     esi, 1
    call    dx_mnemonic
    mov     edi, ebx
    call    dx_rm
    lea     rsi, [rel s_commacl]
    call    dx_puts
    jmp     .done

.f_EIU:                                    ; r/m, imm8 (unsigned)
    call    dx_rd8
    push    rax
    mov     esi, 1
    call    dx_mnemonic
    mov     edi, ebx
    call    dx_rm
    call    dx_sep
    pop     rsi
    call    dx_hex
    jmp     .done

.f_GM:                                     ; lea: reg, [mem] (no size)
    cmp     byte [rel dx_mod], 3
    jne     .gm_ok
    mov     byte [rel dx_fail], 1
    jmp     .done
.gm_ok:
    mov     esi, 1
    call    dx_mnemonic
    mov     edi, ebx
    call    dx_greg
    call    dx_sep
    xor     edi, edi
    call    dx_mem
    jmp     .done

.f_GEI:                                    ; imul reg, r/m, imm
    movzx   eax, byte [rel dx_form]
    cmp     eax, FM_GvEvIz
    je      .gei_z
    call    dx_rd8
    movsx   rax, al
    jmp     .gei_have
.gei_z:
    call    .read_imm_z
.gei_have:
    push    rax
    mov     esi, 1
    call    dx_mnemonic
    mov     edi, ebx
    call    dx_greg
    call    dx_sep
    mov     edi, ebx
    call    dx_rm
    call    dx_sep
    pop     rsi
    call    dx_imm
    jmp     .done

.f_GEx:                                    ; movzx/movsx/movsxd: reg, narrower r/m
    mov     esi, 1
    call    dx_mnemonic
    mov     edi, ebx
    call    dx_greg
    call    dx_sep
    movzx   eax, byte [rel dx_form]
    mov     edi, 8
    cmp     eax, FM_GvEb
    je      .gex_src
    mov     edi, 16
    cmp     eax, FM_GvEw
    je      .gex_src
    mov     edi, 32
.gex_src:
    call    dx_rm
    jmp     .done

.f_IbU:                                    ; int imm8
    call    dx_rd8
    push    rax
    mov     esi, 1
    call    dx_mnemonic
    pop     rsi
    call    dx_hex
    jmp     .done

.f_IbS:                                    ; push imm8 (sign-extended)
    call    dx_rd8
    movsx   rax, al
    push    rax
    mov     esi, 1
    call    dx_mnemonic
    pop     rsi
    call    dx_imm
    jmp     .done

.f_Iz:                                     ; push imm32 (sign-extended)
    call    .read_imm_z
    push    rax
    mov     esi, 1
    call    dx_mnemonic
    pop     rsi
    call    dx_imm
    jmp     .done

.f_Iw:                                     ; ret imm16
    call    dx_rd16
    push    rax
    mov     esi, 1
    call    dx_mnemonic
    pop     rsi
    call    dx_hex
    jmp     .done

.f_xchg:                                   ; xchg r, rax (91-97)
    mov     esi, 1
    call    dx_mnemonic
    mov     edi, ebx
    call    dx_opreg
    call    dx_sep
    mov     edi, ebx
    xor     esi, esi
    call    dx_reg
    jmp     .done

.f_EGI:                                    ; shld/shrd r/m, reg, imm8
    call    .shx_head
    call    dx_rd8
    mov     rsi, rax
    push    rsi
    call    dx_sep
    pop     rsi
    call    dx_hex
    jmp     .done
.f_EGCL:                                   ; shld/shrd r/m, reg, cl
    call    .shx_head
    lea     rsi, [rel s_commacl]
    call    dx_puts
    jmp     .done
.shx_head:
    mov     esi, 1
    call    dx_mnemonic
    mov     edi, ebx
    call    dx_rm
    call    dx_sep
    mov     edi, ebx
    jmp     dx_greg

.f_90:                                     ; nop / pause / xchg r8,rax / xchg ax,ax
    cmp     byte [rel dx_rep], 0
    je      .n90_rex
    lea     rax, [rel s_pause]
    mov     [rel dx_mnem], rax
    jmp     .f_none
.n90_rex:
    test    byte [rel dx_rex], 1
    jnz     .n90_xchg
    cmp     ebx, 16
    je      .n90_xchg
    test    byte [rel dx_rex], 8
    jz      .f_none                        ; plain nop
    lea     rax, [rel s_rexw_nop]          ; 48 90: objdump says "rex.W nop"
    mov     [rel dx_mnem], rax
    jmp     .f_none
.n90_xchg:
    lea     rax, [rel s_xchg]
    mov     [rel dx_mnem], rax
    jmp     .f_xchg

.f_cbw:
    lea     rax, [rel s_cbw]
    cmp     ebx, 16
    je      .cbw_set
    lea     rax, [rel s_cwde]
    cmp     ebx, 32
    je      .cbw_set
    lea     rax, [rel s_cdqe]
.cbw_set:
    mov     [rel dx_mnem], rax
    jmp     .f_none
.f_cwd:
    lea     rax, [rel s_cwd]
    cmp     ebx, 16
    je      .cbw_set
    lea     rax, [rel s_cdq]
    cmp     ebx, 32
    je      .cbw_set
    lea     rax, [rel s_cqo]
    jmp     .cbw_set

.f_str:
    call    dx_string
    jmp     .done

; .read_imm_z: rax = imm16 or imm32 (sign-extended), by operand size
.read_imm_z:
    cmp     ebx, 16
    jne     .rz32
    call    dx_rd16
    movsx   rax, ax
    ret
.rz32:
    call    dx_rd32
    movsxd  rax, eax
    ret

.done:
    pop     rbx
    ret

; ============================================================================
; SSE-family operands
; ============================================================================
; Operand kinds:  V = vector register from ModRM.reg
;                 W = vector register or memory from ModRM.rm
;                 U = vector register from ModRM.rm (register only)
;                 M = memory from ModRM.rm (memory only)
;                 E = general register or memory, G = general register
; Vector registers are mm0-7 (MMX forms) or xmm0-15. General registers are
; 64-bit with REX.W, else 32-bit.

dx_sse_operands:
    push    rbx
    ; REX.W / VEX.W turns a trailing 'd' into 'q' (movd -> movq, ...)
    test    byte [rel dx_sflags], SF_WQ
    jz      .no_wq
    test    byte [rel dx_rex], 8
    jz      .no_wq
    mov     esi, 'q'
    call    dx_name_last
.no_wq:
    ; VEX-only tables: VEX.W turns a trailing 's' into 'd' (ps -> pd)
    cmp     byte [rel dx_vex], 0
    je      .named
    cmp     byte [rel dx_vpfx], 0
    jne     .named
    test    byte [rel dx_sflags], VF_WSD
    jz      .named
    test    byte [rel dx_rex], 8
    jz      .named
    mov     esi, 'd'
    call    dx_name_last
.named:
    movzx   eax, byte [rel dx_form]
    cmp     eax, FM_VW
    je      .VW
    cmp     eax, FM_WV
    je      .WV
    cmp     eax, FM_VWI
    je      .VWI
    cmp     eax, FM_VE
    je      .VE
    cmp     eax, FM_EV
    je      .EV
    cmp     eax, FM_GW
    je      .GW
    cmp     eax, FM_GU
    je      .GU
    cmp     eax, FM_UI
    je      .UI
    cmp     eax, FM_VM
    je      .VM
    cmp     eax, FM_MV
    je      .MV
    cmp     eax, FM_V12
    je      .V12
    cmp     eax, FM_EVI
    je      .EVI
    cmp     eax, FM_VEI
    je      .VEI
    cmp     eax, FM_GUI
    je      .GUI
    cmp     eax, FM_VW0
    je      .VW0
    cmp     eax, FM_CMPS
    je      .CMPS
    cmp     eax, FM_PCLMUL
    je      .PCLMUL
    cmp     eax, FM_ENDBR
    je      .ENDBR
    cmp     eax, FM_XBCAST
    je      .XBCAST
    cmp     eax, FM_XINS
    je      .XINS
    cmp     eax, FM_XEXT
    je      .XEXT
    cmp     eax, FM_XIS4
    je      .XIS4
    cmp     eax, FM_BGBE
    je      .BGBE
    cmp     eax, FM_BGEB
    je      .BGEB
    cmp     eax, FM_BBE
    je      .BBE
    cmp     eax, FM_XMLD
    je      .XMLD
    cmp     eax, FM_XMST
    je      .XMST
    cmp     eax, FM_BRORX
    je      .BRORX
    cmp     eax, FM_XZERO
    je      .XZERO
    jmp     .fail

.VW:
    call    .mn
    call    dx_opV
    call    .nds
    call    dx_sep
    call    dx_opW
    jmp     .done
.WV:
    call    .mn
    call    dx_opW
    call    .movs_nds                      ; vmovss/vmovsd register store
    call    dx_sep
    call    dx_opV
    jmp     .done
.VWI:
    call    .mn
    call    dx_opV
    call    .nds
    call    dx_sep
    call    dx_opW
    jmp     .imm8
.VE:
    call    .mn
    call    dx_opV
    call    .nds
    call    dx_sep
    call    dx_opE
    jmp     .done
.EV:
    call    .mn
    call    dx_opE
    call    dx_sep
    call    dx_opV
    jmp     .done
.GW:
    call    .mn
    call    dx_opG
    call    dx_sep
    call    dx_opW
    jmp     .done
.GU:
    cmp     byte [rel dx_mod], 3
    jne     .fail
    call    .mn
    mov     edi, 32
    call    dx_greg
    call    dx_sep
    call    dx_opW
    jmp     .done
.UI:                                       ; group: the name comes from ModRM.reg
    cmp     byte [rel dx_mod], 3
    jne     .fail
    lea     rax, [rel x86_groups]
    movzx   ecx, word [r12]                ; group number (r12 = SSE entry)
    shl     ecx, 3
    movzx   edx, byte [rel dx_regno]
    and     edx, 7
    add     ecx, edx
    movzx   ecx, word [rax + rcx*4]
    cmp     ecx, 0xFFFF
    je      .fail
    lea     rax, [rel x86_names]
    add     rax, rcx
    mov     [rel dx_mnem], rax
    call    .mn
    cmp     byte [rel dx_vex], 0
    je      .ui_src
    movzx   esi, byte [rel dx_vvvv]        ; VEX: vvvv is the destination
    call    dx_vecreg
    call    dx_sep
.ui_src:
    call    dx_opW
    jmp     .imm8
.VM:
    cmp     byte [rel dx_mod], 3
    je      .fail
    call    .mn
    call    dx_opV
    call    .nds
    call    dx_sep
    call    dx_opW
    jmp     .done
.MV:
    cmp     byte [rel dx_mod], 3
    je      .fail
    call    .mn
    call    dx_opW
    call    dx_sep
    call    dx_opV
    jmp     .done
.V12:                                      ; movlps/movhps, or movhlps/movlhps
    cmp     byte [rel dx_mod], 3
    jne     .VW
    lea     rax, [rel s_movhlps]
    cmp     byte [rel dx_op], 0x12
    je      .v12_name
    lea     rax, [rel s_movlhps]
.v12_name:
    mov     [rel dx_mnem], rax
    jmp     .VW
.EVI:
    call    .mn
    call    dx_opE
    call    dx_sep
    call    dx_opV
    jmp     .imm8
.VEI:
    call    .mn
    call    dx_opV
    call    .nds
    call    dx_sep
    call    dx_opE
    jmp     .imm8
.GUI:
    cmp     byte [rel dx_mod], 3
    jne     .fail
    call    .mn
    mov     edi, 32
    call    dx_greg
    call    dx_sep
    call    dx_opW
    jmp     .imm8
.VW0:
    call    .mn
    call    dx_opV
    call    dx_sep
    call    dx_opW
    lea     rsi, [rel s_commaxmm0]
    call    dx_puts
    jmp     .done

.CMPS:                                     ; cmpps xmm,xmm,imm - or cmpltps xmm,xmm
    call    .peek_imm
    cmp     eax, 32
    jae     .VWI
    cmp     byte [rel dx_vex], 0
    jne     .cmps_pred                     ; VEX: 32 predicates, SSE: 8
    cmp     eax, 8
    jae     .VWI
.cmps_pred:
    ; "cmp" + predicate + the entry's suffix (ps/pd/ss/sd)
    lea     rdi, [rel dx_namebuf]
    mov     byte [rdi], 'c'
    mov     byte [rdi + 1], 'm'
    mov     byte [rdi + 2], 'p'
    add     rdi, 3
    lea     rsi, [rel cmp_preds]
    shl     eax, 4
    add     rsi, rax
.cmps_copy:
    mov     cl, [rsi]
    test    cl, cl
    jz      .cmps_suffix
    mov     [rdi], cl
    inc     rdi
    inc     rsi
    jmp     .cmps_copy
.cmps_suffix:
    mov     rsi, [rel dx_mnem]             ; "cmpps": suffix at +3
    mov     cl, [rsi + 3]
    mov     [rdi], cl
    mov     cl, [rsi + 4]
    mov     [rdi + 1], cl
    mov     byte [rdi + 2], 0
    lea     rax, [rel dx_namebuf]
    mov     [rel dx_mnem], rax
    call    .mn
    call    dx_opV
    call    .nds
    call    dx_sep
    call    dx_opW
    call    dx_rd8                         ; consume the predicate
    jmp     .done

.PCLMUL:                                   ; pclmulqdq: known selectors get names
    call    .peek_imm
    lea     rsi, [rel s_pclmul_ll]
    cmp     eax, 0x00
    je      .pcl_named
    lea     rsi, [rel s_pclmul_hl]
    cmp     eax, 0x01
    je      .pcl_named
    lea     rsi, [rel s_pclmul_lh]
    cmp     eax, 0x10
    je      .pcl_named
    lea     rsi, [rel s_pclmul_hh]
    cmp     eax, 0x11
    jne     .VWI
.pcl_named:
    mov     [rel dx_mnem], rsi
    call    .mn
    call    dx_opV
    call    .nds
    call    dx_sep
    call    dx_opW
    call    dx_rd8
    jmp     .done

; ---- VEX-only forms ----
.XZERO:
    cmp     byte [rel dx_vl], 0
    je      .zero_named
    lea     rax, [rel s_vzeroall]
    mov     [rel dx_mnem], rax
.zero_named:
    xor     esi, esi
    call    dx_mnemonic
    jmp     .done
.XBCAST:                                   ; V, xmm register or memory
    call    .mn
    call    dx_opV
    call    dx_sep
    cmp     byte [rel dx_mod], 3
    jne     .bcast_mem
    movzx   esi, byte [rel dx_rmreg]
    mov     edi, 1
    call    dx_vecreg_c
    jmp     .done
.bcast_mem:
    call    dx_memsize
    cmp     edi, 256
    jne     .mem_done
    mov     edi, 128
    jmp     .mem_done
.XINS:                                     ; ymm, ymm, xmm/m128, imm8
    call    .mn
    call    dx_opV
    call    .vvvv
    call    dx_sep
    call    .xmm_or_m128
    jmp     .imm8
.XEXT:                                     ; xmm/m128, ymm, imm8
    call    .mn
    call    .xmm_or_m128
    call    dx_sep
    call    dx_opV
    jmp     .imm8
.XIS4:                                     ; V, vvvv, W, register from imm8[7:4]
    call    .mn
    call    dx_opV
    call    .vvvv
    call    dx_sep
    call    dx_opW
    call    dx_sep
    call    dx_rd8
    shr     eax, 4
    mov     esi, eax
    call    dx_vecreg
    jmp     .done
.XMLD:                                     ; V, vvvv, memory
    cmp     byte [rel dx_mod], 3
    je      .fail
    call    .mn
    call    dx_opV
    call    .vvvv
    call    dx_sep
    call    dx_opW
    jmp     .done
.XMST:                                     ; memory, vvvv, V
    cmp     byte [rel dx_mod], 3
    je      .fail
    call    .mn
    call    dx_opW
    call    .vvvv
    call    dx_sep
    call    dx_opV
    jmp     .done
.BGBE:                                     ; gpr, vvvv, r/m
    call    .mn
    call    dx_opG
    call    dx_sep
    call    .vvvv_gpr
    call    dx_sep
    call    dx_opE
    jmp     .done
.BGEB:                                     ; gpr, r/m, vvvv
    call    .mn
    call    dx_opG
    call    dx_sep
    call    dx_opE
    call    dx_sep
    call    .vvvv_gpr
    jmp     .done
.BBE:                                      ; group: vvvv, r/m
    lea     rax, [rel x86_groups]
    movzx   ecx, word [r12]
    shl     ecx, 3
    movzx   edx, byte [rel dx_regno]
    and     edx, 7
    add     ecx, edx
    movzx   ecx, word [rax + rcx*4]
    cmp     ecx, 0xFFFF
    je      .fail
    lea     rax, [rel x86_names]
    add     rax, rcx
    mov     [rel dx_mnem], rax
    call    .mn
    call    .vvvv_gpr
    call    dx_sep
    call    dx_opE
    jmp     .done
.BRORX:                                    ; gpr, r/m, imm8
    call    .mn
    call    dx_opG
    call    dx_sep
    call    dx_opE
    jmp     .imm8

; ",vvvv" when this VEX instruction has an extra source register
.nds:
    cmp     byte [rel dx_vex], 0
    je      .nds_ret
    test    byte [rel dx_sflags], SF_NDS
    jz      .nds_ret
    ; vmovss/vmovsd (0F 10): only the register form has one
    cmp     byte [rel dx_map], 2
    jne     .vvvv
    cmp     byte [rel dx_op], 0x10
    jne     .vvvv
    cmp     byte [rel dx_mod], 3
    jne     .nds_ret
.vvvv:
    call    dx_sep
    movzx   esi, byte [rel dx_vvvv]
    jmp     dx_vecreg
.nds_ret:
    ret
; vmovss/vmovsd store (0F 11) register form: W, vvvv, V
.movs_nds:
    cmp     byte [rel dx_vex], 0
    je      .nds_ret
    cmp     byte [rel dx_map], 2
    jne     .nds_ret
    cmp     byte [rel dx_op], 0x11
    jne     .nds_ret
    cmp     byte [rel dx_mod], 3
    jne     .nds_ret
    movzx   eax, byte [rel dx_sflags]
    and     eax, SF_MEM
    cmp     eax, 5
    je      .nds_ret                       ; vmovups & co: no extra source
    jmp     .vvvv
; vvvv as a general register (BMI), 32/64 by VEX.W
.vvvv_gpr:
    mov     edi, 32
    test    byte [rel dx_rex], 8
    jz      .vg
    mov     edi, 64
.vg:
    movzx   esi, byte [rel dx_vvvv]
    jmp     dx_reg
; an xmm register or 128-bit memory operand (vinsert/vextract)
.xmm_or_m128:
    cmp     byte [rel dx_mod], 3
    jne     .m128
    movzx   esi, byte [rel dx_rmreg]
    mov     edi, 1
    jmp     dx_vecreg_c
.m128:
    mov     edi, 128
    jmp     dx_mem
.mem_done:
    call    dx_mem
    jmp     .done

.ENDBR:                                    ; F3 0F 1E FA / FB
    lea     rax, [rel s_endbr64]
    cmp     byte [rel dx_modrm], 0xFA
    je      .endbr_name
    lea     rax, [rel s_endbr32]
    cmp     byte [rel dx_modrm], 0xFB
    jne     .fail
.endbr_name:
    mov     [rel dx_mnem], rax
    xor     esi, esi
    call    dx_mnemonic
    jmp     .done

.imm8:
    call    dx_rd8
    mov     rsi, rax
    push    rsi
    call    dx_sep
    pop     rsi
    call    dx_hex
    jmp     .done

.fail:
    mov     byte [rel dx_fail], 1
.done:
    pop     rbx
    ret

.mn:
    mov     esi, 1
    jmp     dx_mnemonic

; the immediate after the ModRM operand, without consuming it
.peek_imm:
    mov     rcx, [rel dx_cur]
    cmp     rcx, [rel dx_end]
    jae     .peek_fail
    movzx   eax, byte [rcx]
    ret
.peek_fail:
    mov     byte [rel dx_fail], 1
    mov     eax, 0xFF
    ret

; ---- dx_name_last ------------------------
; Copies the mnemonic to dx_namebuf with its last character replaced by
; the character in esi ('q' for movd -> movq, 'd' for ...ps -> ...pd).
dx_name_last:
    mov     edx, esi
    mov     rsi, [rel dx_mnem]
    lea     rdi, [rel dx_namebuf]
.copy:
    mov     al, [rsi]
    mov     [rdi], al
    test    al, al
    jz      .copied
    inc     rsi
    inc     rdi
    jmp     .copy
.copied:
    mov     [rdi - 1], dl
    lea     rax, [rel dx_namebuf]
    mov     [rel dx_mnem], rax
    ret

; ---- vector operand printers ------------

; dx_vecreg: vector register esi ("mm3" / "xmm12")
dx_vecreg:
    movzx   edi, byte [rel dx_vclass]
; dx_vecreg_c: vector register esi of class edi (0 mm, 1 xmm, 2 ymm, 3 zmm)
dx_vecreg_c:
    push    rsi
    push    rdi
    lea     rsi, [rel s_mm]
    test    edi, edi
    jz      .prefix
    lea     rsi, [rel s_xmm]
    cmp     edi, 1
    je      .prefix
    lea     rsi, [rel s_ymm]
    cmp     edi, 2
    je      .prefix
    lea     rsi, [rel s_zmm]
.prefix:
    call    dx_puts
    pop     rdi
    pop     rsi
    test    edi, edi
    jnz     .num
    and     esi, 7
.num:
    mov     rdi, [rel dx_fb]
    jmp     fmt_udec

; dx_memsize: edi = memory operand size in bits for this entry (0 = none)
dx_memsize:
    movzx   eax, byte [rel dx_sflags]
    and     eax, SF_MEM
    ; W makes a DWORD operand QWORD where it also renames the instruction
    ; (pinsrd -> pinsrq, vfmadd213ss -> vfmadd213sd)
    cmp     eax, 3
    jne     .sized
    test    byte [rel dx_rex], 8
    jz      .sized
    test    byte [rel dx_sflags], SF_WQ
    jnz     .wide
    cmp     byte [rel dx_vex], 0
    je      .sized
    cmp     byte [rel dx_vpfx], 0
    jne     .sized
    test    byte [rel dx_sflags], VF_WSD
    jz      .sized
.wide:
    mov     eax, 4
.sized:
    xor     edi, edi
    cmp     eax, 1
    jne     .w
    mov     edi, 8
.w: cmp     eax, 2
    jne     .d
    mov     edi, 16
.d: cmp     eax, 3
    jne     .q
    mov     edi, 32
.q: cmp     eax, 4
    jne     .x
    mov     edi, 64
.x: cmp     eax, 5
    jne     .ret
    mov     edi, 64                        ; by register class: mm / xmm / ymm
    cmp     byte [rel dx_vclass], 0
    je      .ret
    mov     edi, 128
    cmp     byte [rel dx_vclass], 1
    je      .ret
    mov     edi, 256
.ret:
    ret

dx_opV:
    movzx   esi, byte [rel dx_regno]
    cmp     byte [rel dx_narrow], 0
    je      dx_vecreg
    mov     edi, 1                         ; narrowing conversion: always xmm
    jmp     dx_vecreg_c

dx_opW:
    cmp     byte [rel dx_half], 0
    jne     .half
    cmp     byte [rel dx_mod], 3
    jne     .mem
    movzx   esi, byte [rel dx_rmreg]
    jmp     dx_vecreg
.mem:
    call    dx_memsize
    jmp     dx_mem
.half:
    cmp     byte [rel dx_mod], 3
    jne     .half_mem
    movzx   esi, byte [rel dx_rmreg]
    mov     edi, 1                         ; always xmm
    jmp     dx_vecreg_c
.half_mem:
    call    dx_memsize
    cmp     byte [rel dx_vl], 0
    je      .half_put
    add     edi, edi                       ; ymm destination: twice the bytes
.half_put:
    jmp     dx_mem

; E: general register (32/64 by REX.W) or memory (entry size, else 32/64)
dx_opE:
    mov     edi, 32
    test    byte [rel dx_rex], 8
    jz      .sized
    mov     edi, 64
.sized:
    cmp     byte [rel dx_mod], 3
    jne     .mem
    movzx   esi, byte [rel dx_rmreg]
    jmp     dx_reg
.mem:
    push    rdi
    call    dx_memsize
    pop     rax
    test    edi, edi
    jnz     .have
    mov     edi, eax
.have:
    jmp     dx_mem

dx_opG:
    mov     edi, 32
    test    byte [rel dx_rex], 8
    jz      .reg
    mov     edi, 64
.reg:
    jmp     dx_greg

; ---- string instructions ----------------
;
; objdump spells them with explicit operands, e.g.
;   rep stos QWORD PTR es:[rdi],rax
;   movs BYTE PTR es:[rdi],BYTE PTR ds:[rsi]
;   repz cmps BYTE PTR ds:[rsi],BYTE PTR es:[rdi]
;   lods al,BYTE PTR ds:[rsi]        scas al,BYTE PTR es:[rdi]
;
dx_string:
    push    rbx
    movzx   ebx, byte [rel dx_osz]
    movzx   eax, byte [rel dx_op]
    and     eax, 0xFE                      ; A4/A6/AA/AC/AE family

    ; rep prefix spelling
    cmp     byte [rel dx_repne], 0
    je      .no_repne
    lea     rsi, [rel s_repnz]
    jmp     .prefix
.no_repne:
    cmp     byte [rel dx_rep], 0
    je      .mn
    lea     rsi, [rel s_rep]
    cmp     eax, 0xA6                      ; cmps
    je      .repz
    cmp     eax, 0xAE                      ; scas
    jne     .prefix
.repz:
    lea     rsi, [rel s_repz]
.prefix:
    push    rax
    call    dx_puts
    pop     rax
.mn:
    push    rax
    mov     esi, 1
    call    dx_mnemonic
    pop     rax

    cmp     eax, 0xA4
    je      .movs
    cmp     eax, 0xA6
    je      .cmps
    cmp     eax, 0xAA
    je      .stos
    cmp     eax, 0xAC
    je      .lods
    ; scas: acc, es:[rdi]
    call    .acc
    call    dx_sep
    call    .es_rdi
    jmp     .done
.movs:
    call    .es_rdi
    call    dx_sep
    call    .ds_rsi
    jmp     .done
.cmps:
    call    .ds_rsi
    call    dx_sep
    call    .es_rdi
    jmp     .done
.stos:
    call    .es_rdi
    call    dx_sep
    call    .acc
    jmp     .done
.lods:
    call    .acc
    call    dx_sep
    call    .ds_rsi
.done:
    pop     rbx
    ret

.acc:
    mov     edi, ebx
    xor     esi, esi
    jmp     dx_reg
.es_rdi:
    call    .size
    lea     rsi, [rel s_esrdi]
    jmp     dx_puts
.ds_rsi:
    call    .size
    lea     rsi, [rel s_dsrsi]
    jmp     dx_puts
.size:
    lea     rsi, [rel s_byte]
    cmp     ebx, 8
    je      .size_put
    lea     rsi, [rel s_word]
    cmp     ebx, 16
    je      .size_put
    lea     rsi, [rel s_dword]
    cmp     ebx, 32
    je      .size_put
    lea     rsi, [rel s_qword]
.size_put:
    jmp     dx_puts

