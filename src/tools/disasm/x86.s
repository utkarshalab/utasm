; ============================================================================
; X86-64 INSTRUCTION DECODER
; ============================================================================
; Decodes one instruction and writes it in Intel syntax, in the same style
; as `objdump -d -M intel`, so the two can be compared line by line:
;
;     x86_decode(code, available, address, fmtbuf) -> length, branch target
;
; Coverage (stage 1): legacy prefixes, REX, the one-byte map and the 0F map
; for general-purpose instructions (ALU, mov/lea/xchg, push/pop, shifts,
; mul/div, inc/dec/not/neg, test/cmp, jumps/calls/ret, setcc/cmovcc/jcc,
; movzx/movsx/movsxd, bt*, bsf/bsr, shld/shrd, cmpxchg/xadd, bswap,
; string instructions with rep, nop forms, syscall, cpuid, rdtsc, ...).
; Everything else - SSE/AVX, 0F 38 / 0F 3A, x87 - decodes as "(bad)"
; (length 0) for now.
;
; The opcode tables are generated by scripts/gen/gen_x86_tables.py into
; x86_tables.inc; the FM_* / FL_* numbers below must match that script.
;
; Calling convention (AMD64):
;   args  : rdi, rsi, rdx, rcx
;   callee saved: rbx, rbp, r12-r15

; ---- operand forms (FORMS in scripts/gen/gen_x86_tables.py) ----
