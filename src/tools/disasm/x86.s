[SECTION .bss]
align 8
dx_start:   resq 1              ; first byte of the instruction
dx_cur:     resq 1              ; next byte to read
dx_end:     resq 1              ; end of readable bytes (at most 15 on)
dx_addr:    resq 1              ; address of the instruction
dx_fb:      resq 1              ; FmtBuf being written
dx_target:  resq 1              ; direct branch target, or -1
dx_mnem:    resq 1              ; mnemonic string
dx_disp:    resq 1              ; memory displacement (sign-extended)
dx_textpos: resq 1              ; FmtBuf length where this text began
dx_rex:     resb 1              ; REX byte, or 0
dx_rex4:    resb 1              ; APX: R4 X4 B4 (0x40 0x20 0x10) - bit 4 of the registers
dx_rex2:    resb 1              ; 1 = a REX2 prefix (D5) came
dx_nf:      resb 1              ; APX's NF: "{nf} " before the mnemonic
dx_p2:      resb 1              ; EVEX P2, as read
dx_p66:     resb 1
dx_n66:     resb 1              ; number of 66 prefixes (extra ones print data16)
dx_sflags:  resb 1              ; SSE entry flags, 0 for integer instructions
dx_vex:     resb 1              ; 1 = VEX-encoded
dx_vl:      resb 1              ; VEX.L
dx_vvvv:    resb 1              ; VEX.vvvv (already inverted), 0-15
dx_d16w:    resb 1              ; a 66 REX.W overrides written "data16 "
dx_wd16:    resb 1              ; (x86_decode: the instruction's dx_d16w)
dx_vlen:    resq 1
dx_w66at:   resq 1              ; x86_decode: the index of the first 66, or -1              ; dx_variant_clear's trial length
dx_pgnone:  resb 1              ; dx_pgrp: none, and no fallback either
dx_pgnamed: resb 1              ; dx_pgrp's none: the prefixes named
dx_vraw:    resb 1              ; VEX.vvvv as written (inverted, all 4 bits), 0xFF none
dx_vpfx:    resb 1              ; print a "v" before the SSE name
dx_vclass:  resb 1              ; vector registers: 0 mm, 1 xmm, 2 ymm
dx_half:    resb 1              ; widening op: source is half the destination width
dx_narrow:  resb 1              ; narrowing op: xmm destination, source by VEX.L
dx_namebuf: resb 40             ; a mnemonic built at decode time (ccmp's {dfv=..})
dx_p67:     resb 1              ; address-size prefix: 32-bit address registers
dx_map:     resb 1              ; 1 = one-byte map, 2 = 0F map
dx_lock:    resb 1
dx_rep:     resb 1              ; F3
dx_repne:   resb 1              ; F2
dx_seg:     resb 1              ; segment override letter (c,s,d,e,f,g) or 0
dx_fail:    resb 1              ; ran out of bytes / invalid
dx_op:      resb 1              ; opcode byte
dx_form:    resb 1
dx_flags:   resb 1
dx_osz:     resb 1              ; operand size in bits: 8, 16, 32, 64
dx_mod:     resb 1
dx_modrm:   resb 1              ; the raw ModRM byte
dx_regno:   resb 1              ; ModRM.reg with REX.R (0-15)
dx_rmreg:   resb 1              ; ModRM.rm register with REX.B (mod == 3)
dx_base:    resb 1              ; 0-15, NO_REG or RIP_REG
dx_index:   resb 1              ; 0-15 or NO_REG
dx_scale:   resb 1
dx_hasdisp: resb 1
dx_disp8n:  resb 1              ; disp8 scale (EVEX disp8*N), else 1
dx_evex:    resb 1              ; 1 = EVEX-encoded
dx_reghi:   resb 1              ; 16 when EVEX.R' selects vector registers 16-31
dx_rmhi:    resb 1              ; 16 when EVEX.X does (register ModRM.rm)
dx_eaaa:    resb 1              ; EVEX opmask register (0 = none)
dx_ez:      resb 1              ; EVEX.z: zeroing
dx_eb:      resb 1              ; EVEX.b: broadcast / rounding / sae
dx_eround:  resb 1              ; rounding mode (EVEX.L'L with b and registers)
dx_emsize:  resb 1              ; entry memory size class
dx_eflags:  resb 1              ; entry EV_* flags
dx_epred:   resb 1              ; the imm8 is a predicate already in the name
dx_fwait:   resb 1              ; 9B folded into the x87 instruction (fstsw ...)
dx_eflags2: resb 1              ; entry EV2_* flags
dx_riz:     resb 1              ; a SIB with no index objdump writes as riz
dx_vsib:    resb 1              ; VSIB: the index's vector class (1 xmm, 2 ymm, 3 zmm), 0: none
dx_vexp:    resb 1              ; "{vex} " before the mnemonic
alignb 8
dx_port:    resq 1              ; in / out's port (imm8)
; x86_decode's unused prefixes (objdump's names): dx_upfx / dx_urex are
; what dx_mnemonic writes, dx_upend / dx_urend what the trials found
%define DX_TBUF 256
dx_wargs:   resq 4              ; x86_decode's rdi, rsi, rdx, rcx
dx_wavail:  resq 1              ; ... its bytes, at most 15
dx_wf64:    resb 1              ; REX.W on a near call / jmp
dx_trialing: resb 1             ; x86_decode's trial decodes running
dx_ripmem:  resb 1              ; a [rip + disp32] operand was read
dx_mode:    resb 1              ; this instruction's mode: 16, 32 or 64
dx_asz:     resb 1              ; its address size
dx_a16:     resb 1              ; its memory operand is 16-bit addressing
dx_sysfx:   resb 1              ; a suffix for .sys_mem's name (sgdtw), or 0
dx_ewretry: resb 1              ; EVEX: the W0 entry looked up for a W1 (16 / 32)
dx_undef:   resb 1              ; a form found no instruction (dx_fail too): "(bad)"
dx_trunc:   resb 1              ; the bytes ran out (dx_fail too)
dx_sel66:   resb 1              ; a 66 chose an empty SSE column (it is no unused one)
dx_w66:     resb 1              ; (x86_decode: the instruction's dx_sel66)
dx_ssepfx:  resb 1              ; the SSE table's prefix column taken (1: 66)
dx_vexpath: resb 1              ; a VEX / EVEX opcode was read
dx_badk:    resb 1              ; .undef's " {kN}" (an EVEX that is none), or 0
dx_rex2own: resb 1              ; jmpabs / pushp / popp: REX2's own (it is used)
dx_w2own:   resb 1              ; (x86_decode: the instruction's dx_rex2own)
alignb 8
dx_opend:   resq 1              ; dx_cur after the opcode byte, or 0
dx_opstart: resq 1              ; a legacy opcode's first byte (dx_badop), or 0
dx_vexstart: resq 1             ; dx_cur after a C4
alignb 8
dx_after_modrm: resq 1          ; dx_cur after the ModRM byte
dx_markbad: resb 1              ; dx_bad_marks: "/(bad)" after operand n (bit n)
dx_repbad:  resb 1              ; ... the operand written "(bad)" (0xFF: none)
global x86_mode, x86_hex0x
x86_mode:   resb 1              ; the decoder's mode: 16, 32 or 64 (0: 64)
x86_hex0x:  resb 1              ; branch targets as "0x37" (no symbols to name them)
alignb 8
global x86_rip_target
x86_rip_target: resq 1          ; x86_decode: the address [rip + disp] names, or -1
dx_tfb_a:   resb FMTBUF_SIZE    ; the trials' FmtBufs: the instruction,
dx_tfb_b:   resb FMTBUF_SIZE    ; and a variant of it
dx_tbuf_a:  resb DX_TBUF
dx_tbuf_b:  resb DX_TBUF
dx_tbytes:  resb 16             ; the variant's bytes
dx_upfx:    resb 32             ; "fs data16 addr32 "
dx_urex:    resb 16             ; "rex.WRXB "
dx_rsbuf:   resb 128            ; dx_rexstop's text
dx_upend:   resb 32
dx_urend:   resb 16

