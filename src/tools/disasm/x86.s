; ---- EVEX entry flags (EV_* in scripts/gen/gen_x86_tables.py) ----
%define EV_BCST     1           ; EVEX.b with memory: broadcast one element
%define EV_SCALAR   2           ; V and H are xmm whatever the vector length
%define EV_ER       4           ; EVEX.b with registers: rounding control
%define EV_SAE      8           ; EVEX.b with registers: {sae}
%define EV_PINT     16          ; vpcmp predicate in the name
%define EV_PFP      32          ; vcmp predicate in the name
%define EV_NELEM    64          ; disp8*N scales by one element
%define EV_MOVS     128         ; vmovss/vmovsd: H only in the register form
%define EV2_E16     1           ; (the entry's byte 15) broadcast elements of 16 bits;
                                ; with EV_NELEM an element of 2 bytes
%define EV2_E8      2           ; with EV_NELEM an element of 1 byte
%define EV2_REG     4           ; the entry for a register ModRM.rm only
%define EV2_MEM     8           ; ... for memory only
%define EV2_DUP     16          ; vmovddup: 8 bytes of memory at 128 bits
%define EV2_PCOM    128         ; XOP's vpcom: the predicate after "vpcom"
%define EV2_PFPBF   64          ; vcmpbf16: the predicate after "vcmpbf"
%define EV2_HASVEX  32          ; a VEX form reads the same: "{evex}" when nothing
                                ; EVEX-only is used

; SSE entry flags (x86_sse0f / x86_sse38 / x86_sse3a)
%define SF_MEM      7           ; memory size: 1 B, 2 W, 3 D, 4 Q, 5 vector
%define SF_MMX      8           ; mm registers
%define SF_WQ       16          ; REX.W: trailing 'd' of the name becomes 'q'
%define SF_NDS      32          ; VEX: extra source register
%define SF_NOVEX    64
%define SF_INT      0x80        ; an integer instruction: flags are FL_*
%define VF_WSD      8           ; VEX-only tables: VEX.W turns the last 's' into 'd'

; ---- entry flags ----
%define FL_MODRM     1
%define FL_GROUP     2
%define FL_BYTE      4
%define FL_D64       8          ; default 64-bit operand size (push/pop)
%define FL_F64      16          ; always 64-bit (near call/jmp)
%define FL_X32      32          ; 32 bits outside 64-bit mode (vmread / vmwrite)
%define FL_O64      64          ; 64-bit mode's alone (movrs): none in 16 / 32

%define NO_REG      0xFF
%define RIP_REG     0xFE

